/* ---------- theme: 'system' | 'light' | 'dark' (mirrored in localStorage so theme.js can apply it before first paint) ---------- */
const THEME_KEY = 'tagmark-theme';

export function getTheme() {
  try { return localStorage.getItem(THEME_KEY) || 'system'; } catch { return 'system'; }
}

export function setTheme(mode) {
  const root = document.documentElement;
  root.classList.add('theme-anim'); // eases the colour change instead of a hard flash
  if (mode === 'system') root.removeAttribute('data-theme');
  else root.dataset.theme = mode;
  try {
    if (mode === 'system') localStorage.removeItem(THEME_KEY);
    else localStorage.setItem(THEME_KEY, mode);
  } catch { /* storage unavailable */ }
  clearTimeout(setTheme._t);
  setTheme._t = setTimeout(() => root.classList.remove('theme-anim'), 320);
}
